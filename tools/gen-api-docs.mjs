// Regenerates the endpoint index (docs/API.md table and docs/openapi.json) by reading the route files.
// Run from the project root: node tools/gen-api-docs.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const mods = path.join(root, 'server/src/modules');

// file -> [mount prefix, default access]
const FILES = [
  ['auth/routes.js', '/api/auth', 'per-route'],
  ['public/routes.js', '/api/public', 'public'],
  ['intern/routes.js', '/api/intern', 'intern'],
  ['company/routes.js', '/api/company', 'company'],
  ['applications/applicants.js', '/api/company/applications', 'company'],
  ['account/routes.js', '/api/account', 'any signed-in user'],
  ['payments/routes.js', '/api/payments', 'intern'],
  ['payments/callback.js', '/api/payments/mpesa', 'Safaricom (secret URL)'],
  ['admin/routes.js', '/api/admin', 'admin'],
];
// Routes registered through helper functions that a regex cannot see.
const EXTRA = [
  ['GET', '/api/intern/profile/photo', 'intern'], ['POST', '/api/intern/profile/photo', 'intern'],
  ['GET', '/api/intern/profile/cv', 'intern'], ['POST', '/api/intern/profile/cv', 'intern'],
];

const rows = [['GET', '/api/health', 'public'], ['GET', '/api/health/ready', 'public'], ['GET', '/api/csrf', 'public (issues CSRF token)']];
for (const [file, prefix, access] of FILES) {
  const src = fs.readFileSync(path.join(mods, file), 'utf8');
  for (const m of src.matchAll(/router\.(get|post|put|delete|patch)\(\s*'([^']+)'([^\n]*)/g)) {
    let acc = access;
    if (access === 'per-route') acc = /requireAuth/.test(m[3]) ? 'any signed-in user' : 'public';
    const p = (prefix + (m[2] === '/' ? '' : m[2])).replace(/:(\w+)/g, '{$1}');
    rows.push([m[1].toUpperCase(), p, acc]);
  }
}
for (const [m, p, a] of EXTRA) rows.push([m, p, a]);
rows.sort((a, b) => a[1].localeCompare(b[1]) || a[0].localeCompare(b[0]));

const groups = {};
for (const r of rows) {
  const seg = r[1].split('/')[2] || 'misc';
  (groups[seg] ||= []).push(r);
}
let md = '## Endpoint index (generated)\n\n_Generated by `tools/gen-api-docs.mjs` from the route files. "Access" shows who may call it; every private route also rejects suspended accounts._\n';
for (const [g, list] of Object.entries(groups)) {
  md += `\n### /api/${g}\n\n| Method | Path | Access |\n|---|---|---|\n` + list.map((r) => `| ${r[0]} | \`${r[1]}\` | ${r[2]} |`).join('\n') + '\n';
}
const head = fs.readFileSync(path.join(root, 'docs/API.head.md'), 'utf8');
fs.writeFileSync(path.join(root, 'docs/API.md'), `${head}\n${md}`);

const paths = {};
for (const [m, p, a] of rows) {
  (paths[p] ||= {})[m.toLowerCase()] = {
    tags: [p.split('/')[2] || 'misc'], summary: `${m} ${p}`, description: `Access: ${a}.`,
    ...(m !== 'GET' && !p.includes('/mpesa/callback') ? { parameters: [{ name: 'x-csrf-token', in: 'header', required: true, schema: { type: 'string' } }] } : {}),
    responses: { 200: { description: 'Success' }, 401: { description: 'Not signed in' }, 403: { description: 'Forbidden' }, 422: { description: 'Validation error' } },
  };
}
fs.writeFileSync(path.join(root, 'docs/openapi.json'), JSON.stringify({
  openapi: '3.0.3', info: { title: 'The Perfect Intern API', version: '1.0.0', description: 'Route index only: see docs/API.md for request and response conventions. Cookie-session auth (tpi.sid) plus x-csrf-token on non-GET requests.' },
  servers: [{ url: '/' }], paths,
}, null, 2));
console.log(`${rows.length} endpoints documented`);
